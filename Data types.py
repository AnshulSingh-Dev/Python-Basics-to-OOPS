#Data tupes in Python!
#Python recongnizes data types itself when it is declared.
#Integer
x = 1
print(type(x))

#String
Name = "N0T0R10U5"
print(type(Name))

#Complex
Complex = 1j
print(type(Complex))

#Lists
List = ['Jane Doe','John Doe']
print(type(List))

#Tuple (Typle in pyhton are collection of items that can not be changed i.e. sealed lists)
Tuple = ("Jane Doe","John Doe")
print(type(Tuple))

#Dictionary (Dict in python stores vlaues in form of key:value)
Dict = {"Name" : "John", "Last Name" : "Doe"}
print(type(Dict))

#Set (Set in python is an unordered collection of unique items)
Set = {1,2,3,4,5}
print(type(Set))

#Bool (Bool as in Boolean can have only 2 values i.e. True/False)
Bool = True
print(type(Bool))
