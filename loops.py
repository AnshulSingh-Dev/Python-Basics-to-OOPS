'''
Python consists of mainly two kinf of loops
1. while loop
2. for loop
'''
#While loop(this loops keeps running until the condition is true)
number = 1
while number<100:
    print(number)
    number += 1

#For loop(for loop repeats a block of code for fixed number if times)
Number = 1
for Number in range(0,20):
    print(Number)

